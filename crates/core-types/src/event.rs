use crate::{OrderId, Price, Qty, Side, Timestamp};

/// Normalised order-level market data event (ITCH 5.0 semantics).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum EventBody {
    Add {
        order_id: OrderId,
        side: Side,
        price: Price,
        qty: Qty,
    },
    /// Execution of a resting order. The aggressor is on the opposite side.
    Execute {
        order_id: OrderId,
        qty: Qty,
        match_id: u64,
    },
    /// Partial cancellation of `qty` from a resting order.
    Cancel {
        order_id: OrderId,
        qty: Qty,
    },
    Delete {
        order_id: OrderId,
    },
    /// Cancel/replace; the new order loses time priority.
    Replace {
        order_id: OrderId,
        new_order_id: OrderId,
        price: Price,
        qty: Qty,
    },
    /// Execution against non-displayed liquidity; does not mutate the visible book.
    /// `side` is the aggressor side.
    Trade {
        side: Side,
        price: Price,
        qty: Qty,
        match_id: u64,
    },
}

/// One cache line per event so adjacent ring-buffer slots never share a line
/// between producer and consumer.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(C, align(64))]
pub struct MarketEvent {
    pub seq: u64,
    pub exch_ts: Timestamp,
    /// Local receive timestamp in TSC ticks (or ns on targets without a TSC).
    pub recv_tsc: u64,
    pub body: EventBody,
}

const _: () = assert!(core::mem::size_of::<MarketEvent>() == 64);

/// Trade generated by the matching engine or decoded from an execution message.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Fill {
    pub maker_id: OrderId,
    /// [`OrderId::NONE`] when the aggressor is not known (feed-driven executions).
    pub taker_id: OrderId,
    pub maker_side: Side,
    pub price: Price,
    pub qty: Qty,
}

impl Fill {
    #[inline(always)]
    pub const fn aggressor(&self) -> Side {
        self.maker_side.opposite()
    }
}
